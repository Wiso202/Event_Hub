function switchLanguage(lang) {
    localStorage.setItem('selectedLang', lang);
    
    document.querySelectorAll('[data-key]').forEach(el => {
        const key = el.getAttribute('data-key');
        if (translations[lang][key]) {
            if (el.tagName === 'INPUT') {
                el.placeholder = translations[lang][key];
            } else {
                // Gestion spéciale pour le titre principal avec le span bleu
                if (key === 'heroTitle') {
                    const spanColor = lang === 'fr' ? 'même endroit' : 'one place';
                    el.innerHTML = lang === 'fr' ? `Toute l'actualité événementielle au <span class="text-primary">${spanColor}</span>.` : `All event news in <span class="text-primary">${spanColor}</span>.`;
                } 
                else if (key === 'whyTitle') {
                    el.innerHTML = `Pourquoi <span class="text-primary">EventHub</span> ?`;
                }
                else {
                    el.textContent = translations[lang][key];
                }
            }
        }
    });
}

document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('selectedLang') || 'fr';
    switchLanguage(savedLang);
});
